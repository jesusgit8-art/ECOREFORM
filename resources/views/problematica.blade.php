        <section>
            <h2>
                Deforestación: ¿Qué es?
            </h2>

            <p>
                La deforestación es es la pérdida permanente de zonas boscosas debida, principalmente, a actividades humanas como la agricultura,
                la ganadería o la urbanización. Este proceso implica la eliminación total o parcial de árboles y vegetación, lo que altera gravemente
                el equilibrio natural de los ecosistemas. Aunque la tala de árboles puede formar parte de una gestión forestal sostenible, cuando se
                lleva a cabo de manera descontrolada y sin planes de reforestación, se convierte en un problema ambiental de enormes proporciones

            </p>

            <h2>
                Causas de la deforestación
            </h2>

            <p>
                Para entender cómo frenar la deforestación, primero es necesario conocer qué la provoca. Estas son las principales causas que están
                detrás de la pérdida de nuestros bosques.
            </p>

            <p>
                <strong>Agricultura intensiva y ganadería extensiva</strong>
                Uno de los principales motores
                de la deforestación es la expansión agrícola. En muchas regiones del mundo, se talan grandes extensiones de bosque para cultivar
                productos como soja, aceite de palma o para criar ganado. Esto ocurre especialmente en países tropicales, donde la presión por aumentar
                la producción ha llevado a la destrucción de vastos territorios forestales.
            </p>

            <p>
                <strong>Explotación maderera</strong>
                La tala indiscriminada de árboles para la obtención de madera, papel o carbón vegetal es otra de las causas de la deforestación. Cuando
                esta actividad no se regula ni se lleva a cabo de forma responsable, genera una pérdida irreparable de recursos naturales.
            </p>

            <p>
                <strong>Expansión urbana e infraestructuras</strong>
                El crecimiento de ciudades, carreteras, presas y otras infraestructuras también implica la eliminación de bosques. A medida que la
                población mundial crece, aumenta la demanda de suelo y, con ello, la presión sobre los entornos naturales.
            </p>

            <p>
                <strong>Incendios forestales</strong>
                Los incendios, tanto provocados como naturales, son una causa importante de deforestación. En muchos casos, se causan de forma
                intencionada para “limpiar” terrenos con el fin de usarlos posteriormente para actividades productivas.
            </p>

            <h2>
                Consecuencias de la deforestación
            </h2>

            <p>
                La deforestación tiene un impacto profundo en múltiples niveles. Estas son algunas de sus consecuencias más preocupantes:
            </p>

            <ul>

                <li>

                    <strong>Pérdida de biodiversidad</strong>

                    <p>
                        Los bosques albergan una enorme variedad de especies animales y vegetales. Cuando se destruyen estos hábitats,
                        muchas especies desaparecen o se ven obligadas a desplazarse, lo que pone en peligro la biodiversidad mundial.

                    </p>

                </li>

                <li>

                    <strong>Cambio climático</strong>

                    <p>
                        Los árboles cumplen una función esencial en la absorción de dióxido de carbono. Al destruir grandes áreas forestales,
                        se libera CO₂ a la atmósfera y se reduce la capacidad del planeta para absorber gases de efecto invernadero, acelerando
                        así el cambio climático.
                    </p>

                </li>

                <li>

                    <strong>Erosión del suelo</strong>

                    <p>
                        La vegetación actúa como una barrera natural contra la erosión. Sin árboles que lo protejan, el suelo se degrada rápidamente,
                        pierde nutrientes y se vuelve menos fértil.
                    </p>

                </li>

                <li>

                    <strong>Alteración del ciclo del agua</strong>

                    <p>
                        Los bosques influyen en el equilibrio hídrico. La deforestación puede alterar las lluvias, reducir la humedad del suelo y
                        afectar la disponibilidad de agua dulce.
                    </p>

                </li>

            </ul>

        </section>
