        <h2>Plantas ideales para el CBTA No. 35</h2>

        <ul>
            <li>
                <strong>LA LAVANDA: </strong>
                Esta planta propia de la región mediterránea agradece el sol directo, siempre que no sea demasiado
                intenso, y resiste sin necesidad de demasiada agua. Su característico olor, gracias al que es muy
                usada en perfumería, y sus colores morados y azulados.
            </li>

            <br>

            <li>
                <strong>EL CACTUS: </strong>
                La familia Cactaceae aguanta muy bien la sequía por tratarse de plantas desérticas. Esto no
                significa que no necesiten agua para vivir, pero el sustrato debe estar bien seco antes de un
                nuevo riego.
            </li>

            <br>

            <li>
                <strong>LA VERBENA: </strong>
                Aguanta altas temperaturas y además otorga un aspecto más colorido y vistoso, Además de soportar
                bien la falta de agua, un riego a la semana es suficiente, aguantan muy bien la exposición directa
                al sol (de ahí que sean también muy utilizadas en las medianas de autopistas).
            </li>

            <br>

            <li>
                <strong>EL ÁGAVE: </strong>
                Esta planta oriunda de México y Estados Unidos, también conocida como pita, maguey o mezcal,
                necesitan suelos arcillosos y permeables, además de una alta exposición al sol a lo largo del año.
                Resisten bien la falta de agua.
            </li>
        </ul>

