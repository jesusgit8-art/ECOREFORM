            <h3>Árboles ideales para el CBTA No. 35</h3>

            <ul>
                <li>
                    <strong>FRESNO: </strong>
                    El fresno es un árbol que se adapta a cualquier ambiente y tipo de suelo. Suele distribuirse por
                    las riberas de los ríos y zonas húmedas, pero también puede verse en las montañas. Y es que este
                    árbol aguanta muy bien el frio invierno siendo capaz de vivir entre los 80 y 100 años.
                </li>

                <br>

                <li>
                    <strong>JACARANDA: </strong>
                    La Jacaranda es una especie que destaca por su resistencia y por su bajo consumo de agua,
                    lo que le permite adaptarse y crecer sin necesitar demasiados cuidados. Con un riego adecuado
                    y constante, puede desarrollarse de manera saludable y alcanzar grandes dimensiones.
                    También aporta beneficios al medio ambiente, ya que absorbe dióxido de carbono y produce
                    oxígeno, ayudando a mejorar la calidad del aire. En las zonas urbanas, su presencia favorece
                    la creación de espacios más frescos, contribuyendo a disminuir la temperatura del entorno.
                    Por estas razones, la Jacaranda es una especie muy apropiada para la reforestación de las
                    ciudades, pues además de brindar belleza con sus flores, ofrece ventajas ecológicas que
                    benefician a la población.
                </li>
            </ul>

