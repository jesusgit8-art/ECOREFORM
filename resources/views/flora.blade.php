        <h2>Suelos del CBTA No. 35</h2>
        <p>
            Aunque no existe información específica sobre los suelos del CBTA No. 35, existe información sobre Valle
            de Chalco Solidaridad, que es donde se encuentra ubicado el plantel.
        </p>

        <p>
            El territorio de Valle de Chalco se compone por rocas de origen sedimentario e ígneas extrusivas
            pertenecientes al periodo cenozoico; las unidades litológicas presentes son las siguientes: brecha
            volcánica básica Q(Bvb), toba básica Ts(Tb), aluvial Q(al) y lacustre Q(la).
        </p>

        <p>
            El suelo predominante es el lacustre con 3,958 ha (85% del municipio) constituido por espesas capas
            de material arcilloso, con alto contenido de agua, muy compresibles, dentro de esta clase se localiza
            la zona urbana; le siguen en orden de importancia el suelo aluvial con 396 ha (9%) su localización es
            en el cráter del Volcán de Xico y en la cima del cerro del Márquez; el suelo toba básica se distribuye
            en 193 ha (5%) localizadas en las laderas de los cerros Xico, El Márquez y La Caldera, estos suelos
            por ser de textura arenosa al entrar en contacto con el agua pluvial, pueden provocar inestabilidad en
            laderas; el restante 1% (57 ha) lo compone el suelo brecha volcánica básica.
        </p>

        <h3>TOPONIMIA</h3>
        <p>
            Toma el nombre debido a que se encontraba ubicado en un valle el que era lecho del antiguo Lago
            de Chalco y en este lugar dio inicio el Programa Nacional de Solidaridad.
            Está compuesto por dos glifos de origen prehispánico y un logo contemporáneo. El glifo de Xico o
            Xico, xitli (ombligo) y el glifo calli (casa o casas). El logo es el utilizado por el gobierno federal en el
            Programa Nacional de Solidaridad. El significado es "las casas que se establecieron al lado del Cerro
            de Xico, fundado con la solidaridad de sus pobladores"

        </p>

        <h3>UBICACIÓN GEOGRÁFICA</h3>
        <p>
            Se ubica en la cuenca oriente del Valle de México, cuenta con una latitud mínima de 19°13'30'' y
            máxima de 19°20'21''; con una longitud mínima de 99°42'03'' y máxima de 98°58'34''; altitud de 2 235
            metros sobre el nivel medio del mar.
        </p>

        <h3>LÍMITES Y EXTENSIÓN TERRITORIAL</h3>
        <p>
            El municipio colinda al norte con los Municipios de La Paz e Ixtapaluca; al este con los Municipios
            de Ixtapaluca y Chalco; al sur con el Municipio de Chalco y la Ciudad de México; al oeste con la
            Ciudad de México.
        </p>

        <p>
            El territorio del Municipio comprende y se encuentra asentado conforme a los límites de la poligonal
            siguiente: Conserva la extensión y límites actualmente reconocidos y establecidos conforme a la Ley:
            inicia en el punto donde concluye la línea del ferrocarril México-Cuautla y la carretera federal MéxicoPuebla, sobre la carretera se dirige hacia el sureste hasta una distancia de mil metros, donde se
            ubica el río la compañía cuyo cauce sigue en dirección sureste, cruza la autopista México-Puebla y
            la cual continúa con rumbo suroeste hasta interceptar con la Avenida Solidaridad la cual sigue en
            dirección sureste aproximadamente novecientos metros donde dobla en dirección suroeste siguiendo
            el límite del parque metropolitano. Al llegar al Cerro del Marqués lo bordea continuando el camino de
            pavimento en su vertiente sur hasta donde inicia el Cerro de Xico, continúa hacia el sur siguiendo el
            límite entre los ejidos de Chalco y San Martín Xico hasta encontrarse con la carretera ChalcoTláhuac; la cual sigue en dirección oriente hasta pasar la curva de dicha carretera, a una distancia
            aproximadamente de quinientos metros, dobla en dirección sur hasta encontrarse con el río de
            Amecameca, continúa siguiendo su cauce hasta el límite con la Ciudad de México en la zona oeste,
            sigue por dicho límite en dirección norte hasta la autopista México-Puebla, sobre esta dobla hacia el
            noroeste hasta el volcán la caldera, el cual bordea en su vertiente sur hacia una distancia aproximada
            de ochocientos metros desde donde se dirige al sureste hasta encontrarse con la línea del ferrocarril
            México- Cuautla, la cual continúa en dirección noroeste hasta el punto de origen en la poligonal.
        </p>

        <h3>EDAFOLOGÍA</h3>
        <p>
            El suelo dominante es xolonchacgleyico (zg) con 2.540 ha (55% del municipio) formado a partir de
            carbonatos álcali blanco o bietequezquite; otro tipo de suelo presente es el gley sol molido(gm) con
            1,070 ha (23%) su localización es al sur del municipio es la clase se distingue por ser un suelo
            pantanoso con alto contenido de arcilla; la composición del suelo es complementada con la presencia
            de regosoleutrico (Re) formado por sedimentos arenosos se encuentra en 1.026 ha (22%)ubicada
            en la porción noroeste del municipio.

        </p>

        <p>En síntesis, el tipo de suelo existente en la mayor parte del territorio presenta una alta
            compresibilidad mostrando una resistencia promedio de dos toneladas por metro cuadrado; en
            temporadas de lluvias el material presente absorbe gran cantidad de agua, aumentando hasta el
            doble de su volumen original, el cual se reduce a la cuarta parte cuando se deshidrata por completo
            provocando agrietamiento en el terreno, dañando así las construcciones existentes.</p>

        <h3>CLIMA</h3>
        <p>
            Dentro del Municipio de Valle de Chalco Solidaridad, predomina el clima C (WO) (W) B (I”) que es
            templado húmedo, subhúmedo, sin embargo, en la parte norte del Municipio se encuentra también
            clima seco. Durante los meses de diciembre, enero, febrero y marzo, los vientos adquieren
            mayores velocidades y producen polvaredas en las horas más calientes del día.
        </p>

        <p>
            La temperatura media anual es de 15.6°C, pero en el verano, la temperatura promedio máxima
            alcanza los 31°C y en invierno, la mínima promedio es de 8.2°C. No obstante, pueden registrarse
            temperaturas más altas o bajas a lo largo del día. La temperatura más elevada se presenta en los
            meses de abril, mayo, junio, julio y agosto, mientras que las medias mínimas son en diciembre, enero
            y febrero con la presencia de algunas heladas. En ocasiones, bajas temperaturas se han registrado
            en el verano en algunos días de julio y agosto por la disminución de la humedad del aire; y en los
            meses de septiembre y octubre se pueden presentar, durante el día temperaturas altas y por la noche
            vientos fríos.
        </p>

        <p>
            En los meses de mayo, junio, julio, agosto y septiembre las lluvias pueden llegar a ser muy
            abundantes. La precipitación promedio se establece entre 600 y 700 milímetros anuales, mientras
            que la evapotranspiración es muy alta, de 737 milímetros anuales, alcanzando sus valores
            máximos de mayo a octubre, cifra mayor a la precipitación media anual, con excepción de los
            meses lluviosos de agosto a octubre. Los meses secos son: enero, febrero y marzo, aunque se
            registran algunas lluvias extemporáneas.
        </p>

        <p>
            Los vientos predominantes tienen una dirección de sur a norte con velocidades de 2 a 12 m/seg.
            Sin embargo, durante los meses de febrero y marzo adquieren mayores velocidades y producen
            polvaredas en las horas más calientes del día, transportando grandes cantidades de polvo.
        </p>

        <h3>USO DEL SUELO</h3>
        <p>
            Los suelos del Municipio formaron parte de un lago de 15 metros de profundidad en
            tiempos pleistocénicos, el cual se azolvó por fenómenos de deposición lacustre eólica y
            aluvial de diferentes materiales, entre los que predominan las cenizas volcánicas. En sus
            sus comunidades y su entorno, logrando entre otros beneficios reducir las tasas de mortalidad
            y morbilidad.
        </p>

        <p>
            El objetivo general del Municipio de Valle de Chalco Solidaridad, es contar con un sistema de
            salud estable que atienda de manera satisfactoria las necesidades prioritarias de la población a
            partir de la creación de mecanismos de cooperación y coordinación interinstitucional, así como
            de control del ejercicio de los recursos, que contribuyan a consolidar mejores resultados de
            bienestar. En este mismo sentido, adquieren vital importancia, la vigilancia epidemiológica
            permanente, la prevención de situaciones de riesgo, la dignificación de la infraestructura en
            salud, el fortalecimiento de la calidad de la atención y el diseño de campañas de sensibilización
            ciudadana para el autocuidado de la salud.
        </p>
